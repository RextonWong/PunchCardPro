import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import * as XLSX from 'xlsx';

const baseUrl = process.env.QA_BASE_URL || 'http://127.0.0.1:5173';
const month = new Date().toISOString().slice(0, 7);
const fixtureModule = `
const month = '${month}';
const site = { id: 'site-1', name: 'Sample Worksite', rate: 80, rain_min: 4, l_start: '13:00:00', l_end: '14:00:00', l_threshold: '14:30:00', f_start: '13:00:00', f_end: '14:00:00', f_threshold: '14:30:00' };
const entries = ['LD/2','LD:2'].map((lorry, index) => ({ id: 'entry-' + index, workplace_id: 'site-1', lori_id: lorry, date: month + '-01', time_range: '0800-1700', hours: 8, rest: 1, total: 640, is_rain: false }));
const query = (table) => { window.qaReadCount = (window.qaReadCount || 0) + 1; const result = { data: table === 'workplaces' ? [site] : [...entries, ...JSON.parse(localStorage.getItem('qa-remote-entries') || '[]')], error: null }; const chain = new Proxy({}, { get(_target, prop) { return prop === 'then' ? (resolve, reject) => Promise.resolve(result).then(resolve, reject) : () => chain; }}); return chain; };
export const isLocalSupabase = true;
export const supabase = { auth: { getSession: async () => ({ data: { session: window.qaLoggedOut ? null : { user: { id: 'sample-user', email: 'sample@example.com' } } } }), onAuthStateChange: () => ({ data: { subscription: { unsubscribe() {} } } }), signInWithPassword: async () => ({ error: null }) }, from: query,
 functions: { invoke: async (_name, { body }) => {
   if (body.action === 'request') return { data: { challenge_id: '12345678-1234-1234-1234-123456789012', expires_at: new Date(Date.now()+300000).toISOString(), resend_at: new Date(Date.now()+60000).toISOString(), message: 'If eligible, a verification code has been sent.' }, error: null };
   if (body.code !== '123321') return { error: { context: { json: async () => ({ error: 'Incorrect code. Try again.', attempts_remaining: 2 }) } } };
   return { data: { message: body.purpose === 'signup' ? 'Email verified. Your account is ready. Sign in to continue.' : 'Password changed. Sign in with your new password.' }, error: null };
 }} };
`;
mkdirSync('scripts/screenshots', { recursive: true });
const baselinePath = 'src/.qa-baseline.jsx';
writeFileSync(baselinePath, execFileSync('git', ['show', 'origin/main:src/App.jsx']));
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
  await page.clock.install();
  await page.route('**/src/supabaseClient.js', (route) => route.fulfill({ contentType: 'application/javascript', body: fixtureModule }));
  await page.route('**/src/App.jsx', async (route) => {
    const response = await route.fetch({ url: `${baseUrl}/src/.qa-baseline.jsx` });
    await route.fulfill({ response });
  });
  await page.goto(baseUrl);
  await page.getByText('Sample Worksite').click();
  await page.screenshot({ path: 'scripts/screenshots/panels-before.png', fullPage: false });
  await page.unroute('**/src/App.jsx');
  await page.reload();
  await page.getByText('Sample Worksite').click();
  const panels = page.locator('.xl\\:grid-cols-2 > div');
  const sizes = await panels.evaluateAll((elements) => elements.map((element) => element.getBoundingClientRect().width));
  assert.equal(sizes.length, 2);
  assert.ok(Math.abs(sizes[0] - sizes[1]) < 1, `Unequal panel widths: ${sizes}`);
  await page.screenshot({ path: 'scripts/screenshots/panels-after.png', fullPage: false });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Excel Export' }).click();
  const download = await downloadPromise;
  const workbook = XLSX.read(readFileSync(await download.path()));
  assert.equal(workbook.SheetNames.length, 2);
  assert.notEqual(workbook.SheetNames[0], workbook.SheetNames[1]);
  await page.getByRole('link', { name: 'download the Excel file' }).waitFor();
  const retryDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'download the Excel file' }).click();
  assert.equal((await retryDownload).suggestedFilename(), download.suggestedFilename());
  await page.locator('input[type="month"]').fill('2025-01');
  assert.equal(await page.getByRole('button', { name: 'Excel Export' }).isDisabled(), true);
  await page.locator('input[type="month"]').fill(month);
  assert.equal(await page.getByRole('button', { name: 'Refresh data' }).count(), 0);
  const readCount = await page.evaluate(() => window.qaReadCount);
  await page.evaluate(() => { window.dispatchEvent(new Event('focus')); window.dispatchEvent(new Event('online')); document.dispatchEvent(new Event('visibilitychange')); });
  await page.clock.fastForward(31000);
  assert.equal(await page.evaluate(() => window.qaReadCount), readCount, 'Focus and elapsed time must not refresh data');
  await page.evaluate((selectedMonth) => localStorage.setItem('qa-remote-entries', JSON.stringify([{ id: 'remote', workplace_id: 'site-1', lori_id: 'REMOTE', date: selectedMonth + '-01', time_range: '0800-1700', hours: 8, rest: 1, total: 640, is_rain: false }])), month);
  await page.reload();
  await page.getByText('Sample Worksite').click();
  await page.getByText('Lorry REMOTE', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Ledger', exact: true }).click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: 'scripts/screenshots/ledger-phone-after.png', fullPage: true });
  await page.close();

  const login = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await login.addInitScript(() => { window.qaLoggedOut = true; });
  await login.route('**/src/supabaseClient.js', (route) => route.fulfill({ contentType: 'application/javascript', body: fixtureModule }));
  await login.goto(baseUrl);
  await login.getByRole('button', { name: 'No account? Create one' }).click();
  await login.getByLabel('Email', { exact: true }).fill('sample@example.com');
  await login.getByLabel('Password', { exact: true }).fill('StrongPassword123!');
  await login.getByLabel('Confirm Password', { exact: true }).fill('StrongPassword123!');
  await login.getByRole('button', { name: 'Send verification code' }).click();
  await login.getByLabel('Verification code').fill('000000');
  await login.getByRole('button', { name: 'Verify & Create Account' }).click();
  await login.getByText('Incorrect code. Try again.').waitFor();
  await login.getByLabel('Verification code').fill('123321');
  await login.screenshot({ path: 'scripts/screenshots/signup-phone-after.png', fullPage: true });
  await login.getByRole('button', { name: 'Verify & Create Account' }).click();
  await login.getByText('Email verified. Your account is ready. Sign in to continue.').waitFor();
  await login.getByRole('button', { name: 'Forgot password?' }).click();
  await login.getByRole('button', { name: 'Send verification code' }).click();
  await login.getByLabel('New Password', { exact: true }).fill('AnotherPassword123!');
  await login.getByLabel('Confirm Password', { exact: true }).fill('AnotherPassword123!');
  await login.getByLabel('Verification code').fill('123321');
  await login.screenshot({ path: 'scripts/screenshots/recovery-phone-after.png', fullPage: true });
  await login.getByRole('button', { name: 'Verify & Reset Password' }).click();
  await login.getByText('Password changed. Sign in with your new password.').waitFor();
  console.log('PASS: readable browser downloads; equal panels; no phone overflow; data refreshes on page reload with no polling/focus refresh or Refresh button; signup/recovery screens and error feedback. Auth API responses mocked for UI proof.');
} finally {
  await browser.close();
  unlinkSync(baselinePath);
}
